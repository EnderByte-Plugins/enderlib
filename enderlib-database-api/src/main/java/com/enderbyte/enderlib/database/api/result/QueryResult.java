package com.enderbyte.enderlib.database.api.result;

import java.util.List;
import java.util.Optional;
import java.util.stream.Stream;

/**
 * The materialised result of a query.
 *
 * <pre>{@code
 * QueryResult result = database.queryAsync("SELECT * FROM players WHERE uuid = ?", uuid).join();
 *
 * result.isEmpty();
 * result.size();
 * result.first().ifPresent(row -> row.getString("name"));
 *
 * PlayerData player = result.first(PlayerData.class).orElse(null);
 * List<PlayerData> players = result.map(PlayerData.class);
 * }</pre>
 *
 * <p>Every row is read before the connection is released, so a result never keeps a connection
 * checked out. Results are immutable and safe to hand to the server thread.
 */
public interface QueryResult extends Iterable<Row> {

    /** @return the first row, or empty when the query matched nothing */
    Optional<Row> first();

    /** @return the first row, or {@code null}; convenient in code that already null-checks */
    Row firstOrNull();

    /** @return all rows, immutable */
    List<Row> all();

    boolean isEmpty();

    int size();

    /** @return a stream over the rows */
    Stream<Row> stream();

    /**
     * Maps the first row onto an annotated entity type.
     *
     * @param type entity class annotated with {@link com.enderbyte.enderlib.database.api.mapping.Table}
     * @param <T>  entity type
     * @return the mapped entity, or empty
     */
    <T> Optional<T> first(Class<T> type);

    /** Maps the first row with an explicit mapper. */
    <T> Optional<T> first(RowMapper<T> mapper);

    /**
     * Maps every row onto an annotated entity type.
     *
     * @param type entity class
     * @param <T>  entity type
     * @return the mapped entities, immutable
     */
    <T> List<T> map(Class<T> type);

    /** Maps every row with an explicit mapper. */
    <T> List<T> map(RowMapper<T> mapper);

    /**
     * @return the single value of a one-column, one-row result, converted to {@code type}.
     *         The natural fit for {@code SELECT COUNT(*)} and similar.
     */
    <T> Optional<T> value(Class<T> type);

    /**
     * @return keys generated by an {@code INSERT}, when the statement was executed with generated
     *         key retrieval; empty otherwise
     */
    List<Object> generatedKeys();
}
